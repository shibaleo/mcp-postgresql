import { build } from "esbuild";
import path from "path";
import { readFileSync } from "fs";

// Read package.json to externalize all npm dependencies
const pkg = JSON.parse(readFileSync("package.json", "utf-8"));
const external = [
  ...Object.keys(pkg.dependencies || {}),
  ...Object.keys(pkg.devDependencies || {}),
];

await build({
  entryPoints: ["src/server-entry.ts"],
  bundle: true,
  platform: "node",
  target: "node20",
  format: "esm",
  outfile: "api/_bundle.mjs",
  alias: { "@": path.resolve("src") },
  // Keep npm packages external — Vercel NFT will trace them
  external,
  loader: { ".json": "json" },
  // Resolve the dev/prod switch in public-config.ts for the server bundle.
  // This build only ever runs for a deployed (production) Function, so PROD=true.
  // The Vite dev server resolves import.meta.env itself (PROD=false) via ssrLoadModule.
  define: {
    "import.meta.env.PROD": "true",
    "import.meta.env.DEV": "false",
    "import.meta.env.MODE": '"production"',
  },
  banner: { js: "// Auto-generated by scripts/build-api.mjs — do not edit" },
});

console.log("✓ API bundled → api/_bundle.mjs");
